/**
 * Fisher-Yates array shuffler
 */
export function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Get randomized questions for a given category
 */
export function getQuestionsForCategory(category: GrammarCategory): TenseQuestion[] {
  let pool: TenseQuestion[] = [];
  switch (category) {
    case 'irregular-past':
      pool = IRREGULAR_PAST_QUESTIONS;
      break;
    case 'past-participle':
      pool = PAST_PARTICIPLE_QUESTIONS;
      break;
    case 'comparative-superlative':
      pool = COMPARATIVE_QUESTIONS;
      break;
    case 'irregular-plurals':
      pool = IRREGULAR_PLURAL_QUESTIONS;
      break;
    case 'spelling-rules':
      pool = SPELLING_RULE_QUESTIONS;
      break;
    case 'all':
    default:
      pool = ALL_TENSE_QUESTIONS;
      break;
  }
  return shuffleArray(pool);
}
